PREFIXES = ("(재)", "(주)", "(사)", "(특)", "(법)")
SUFFIXES = ("(주)",)


def load_official_names() -> set[str]:
    with CSV_PATH.open(encoding="utf-8") as f:
        return {row["기관명"].strip() for row in csv.DictReader(f) if row.get("기관명")}


def normalize_target(name: str, official: set[str]) -> str | None:
    if name in official:
        return name
    # 단일 후보 부분일치
    candidates = [n for n in official if name in n or n.replace(" ", "") == name.replace(" ", "")]
    if len(candidates) == 1:
        return candidates[0]
    # (주) 보정
    if not name.endswith("(주)"):
        cand = name + "(주)"
        if cand in official:
            return cand
    if name.endswith("(주)"):
        cand = name[:-3]
        if cand in official:
            return official  # noqa: RET504
    return None


def strip_legal(name: str) -> str:
    n = name.strip()
    for p in PREFIXES:
        if n.startswith(p):
            n = n[len(p) :]
    if n.startswith("재단법인 "):
        n = n[len("재단법인 ") :]
    if n.startswith("학교법인"):
        n = n[len("학교법인") :]
    for s in SUFFIXES:
        if n.endswith(s):
            n = n[: -len(s)]
    return n.strip()


def auto_aliases(official_name: str) -> list[str]:
    out: list[str] = []
    base = strip_legal(official_name)
    if base and base != official_name:
        out.append(base)
    if official_name.startswith("한국") and len(official_name) > 2:
        out.append(official_name[2:])
    if official_name.startswith("국립") and len(official_name) > 2:
        out.append(official_name[2:])
    if official_name.startswith("대한") and len(official_name) > 2:
        out.append(official_name[2:])
    if "대학교병원" in official_name:
        out.append(official_name.replace("대학교", ""))
    if "대학교치과병원" in official_name:
        out.append(official_name.replace("대학교", ""))
    if official_name.endswith("주식회사"):
        out.append(official_name.replace("주식회사", "").strip())
    if "·" in official_name:
        out.append(official_name.replace("·", ""))
    return out


def build() -> dict[str, str]:
    official = load_official_names()
    aliases: dict[str, str] = {"_comment": COMMENT}
    conflicts: list[tuple[str, str, str]] = []

    def add(alias: str, target: str, *, manual: bool) -> None:
        alias = alias.strip()
        if not alias or alias.startswith("_"):
            return
        resolved = normalize_target(target, official)
        if resolved is None:
            if manual:
                print(f"[skip] manual target not in CSV: {alias!r} -> {target!r}")
            return
        if alias in aliases and aliases[alias] != resolved:
            if manual:
                aliases[alias] = resolved
            else:
                conflicts.append((alias, aliases[alias], resolved))
            return
        aliases[alias] = resolved

    for alias, target in MANUAL.items():
        add(alias, target, manual=True)

    for name in sorted(official):
        for alias in auto_aliases(name):
            add(alias, name, manual=False)

    covered = {v for k, v in aliases.items() if not k.startswith("_")}
    for name in sorted(official - covered):
        add(strip_legal(name) or name, name, manual=False)

    if conflicts:
        print(f"[info] auto alias conflicts skipped: {len(conflicts)}")
    return aliases


def main() -> None:
    result = build()
    OUT_PATH.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    count = len([k for k in result if not k.startswith("_")])
    targets = len(set(result.values()) - {COMMENT})
    print(f"Wrote {OUT_PATH}")
    print(f"aliases: {count}, unique institutions covered: {targets}")


if __name__ == "__main__":
    main()
